function genProducts(maxNumProducts: number) {
  const products = [];
  for (let i = 0; i < productTypes.length; i++) {
    for (let j = 0; j < colors.length; j++) {
      for (let k = 0; k < sizes.length; k++) {
        for (let l = 0; l < manufacturers.length; l++) {
          products.push({
            id:
              i * colors.length * sizes.length * manufacturers.length +
              j * sizes.length * manufacturers.length +
              k * manufacturers.length +
              l +
              1,
            name: `${colors[j]} ${sizes[k]} ${manufacturers[l]} ${productTypes[i]}`,
          });

          if (
            !Number.isNaN(maxNumProducts) &&
            maxNumProducts &&
            products.length >= maxNumProducts
          )
            return products;
        }
      }
    }
  }

  return products;
}

if (require.main === module) {
  const dataDir = `${__dirname}/../data`;
  fs.mkdirSync(dataDir, {recursive: true});
  const products = genProducts(parseInt(process.argv[2]));
  fs.writeFileSync(
    `${dataDir}/products.json`,
    JSON.stringify(products, null, 2)
  );
  console.log(`Generated ${products.length} products`);
}
